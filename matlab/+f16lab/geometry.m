function group=geometry(ax)
% Silueta docente original, no CAD del avión real.
group=hgtransform('Parent',ax);xx=[7.4 4 1 -4 -7.4];rad=[.03 .55 .85 .7 .12];n=14;v=zeros(5*n,3);a=(0:n-1)'*2*pi/n;
for i=1:5,ids=(i-1)*n+(1:n);v(ids,:)=[repmat(xx(i),n,1),rad(i)*cos(a),rad(i)*sin(a)];end
faces=zeros(4*n,4);k=0;for i=1:4,for j=1:n,jj=mod(j,n)+1;k=k+1;faces(k,:)=[(i-1)*n+j,(i-1)*n+jj,i*n+jj,i*n+j];end,end
patch('Parent',group,'Vertices',v,'Faces',faces,'FaceColor',[.63 .69 .75],'EdgeColor','none');
polys={ [2 .6 .2;-3.2 4.57 .25;-4.2 4.57 .25;-3 .6 .2], ...
 [2 -.6 .2;-3.2 -4.57 .25;-4.2 -4.57 .25;-3 -.6 .2], ...
 [-4.5 .5 0;-6.5 2.7 .1;-7.3 2.3 .1;-6.8 .5 0], ...
 [-4.5 -.5 0;-6.5 -2.7 .1;-7.3 -2.3 .1;-6.8 -.5 0], ...
 [-4 0 -.5;-5.4 0 -3.3;-6.9 0 -3;-7.2 0 -.3], ...
 [4 -.35 -.5;4 .35 -.5;1 .45 -.9;1 -.45 -.9]};
for k=1:numel(polys),patch('Parent',group,'Vertices',polys{k},'Faces',1:4,'FaceColor',[.35 .44 .55],'EdgeColor',[.22 .28 .36]);end
end
